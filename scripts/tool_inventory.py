"""Generate and verify tool inventory (local gate; prevents doc drift).

Usage:
    $env:PYTHONPATH="."; python scripts/tool_inventory.py          # rewrite both targets
    $env:PYTHONPATH="."; python scripts/tool_inventory.py --check  # compare files; exit 1 on mismatch

Targets:
    docs/TOOL_INVENTORY.md                     — full per-tool table (repo)
    website/docs/_generated/toolset-matrix.md  — totals + toolset table (site snippet)

Inventory is generated from registry only. Description = first line truncated; params from input_schema.properties.
"""
from __future__ import annotations

import sys
from pathlib import Path

from cadmcp.registry import TOOLSET_DEFS
from cadmcp.toolsets.core import core_registry

TARGET = Path("docs/TOOL_INVENTORY.md")
SITE_TARGET = Path("website/docs/_generated/toolset-matrix.md")
DESC_LIMIT = 100


def _cell(text: str) -> str:
    """Flatten arbitrary text to a single-line table cell."""
    line = text.strip().splitlines()[0] if text.strip() else ""
    if len(line) > DESC_LIMIT:
        line = line[: DESC_LIMIT - 1] + "…"
    return line.replace("|", "\\|")


def _params(schema: dict) -> str:
    props = schema.get("properties") or {}
    required = set(schema.get("required") or ())
    if not props:
        return "—"
    cells = [f"`{name}`{'*' if name in required else ''}" for name in props]
    return ", ".join(cells)


def render() -> str:
    specs = core_registry().all()
    groups: dict[str, list] = {}
    for spec in specs:
        groups.setdefault(spec.toolset, []).append(spec)

    lines = [
        "# Tool inventory (auto-generated)",
        "",
        "> Generated by `python scripts/tool_inventory.py` from registry — **do not edit by hand**.",
        "> Verify: `python scripts/tool_inventory.py --check` (exit 1 on mismatch).",
        "",
        f"- Total tools: **{len(specs)}**",
        f"- Toolsets: **{len(groups)}**",
        "- Params column: `name` optional, `name*` required.",
        "",
        "| toolset | tools | description |",
        "|---|---|---|",
    ]
    for name in sorted(groups):
        lines.append(f"| {name} | {len(groups[name])} | {_cell(TOOLSET_DEFS.get(name, ''))} |")

    for name in sorted(groups):
        lines += ["", f"## {name} ({len(groups[name])})", ""]
        lines += ["| tool | mutating | params | description |", "|---|---|---|---|"]
        for spec in groups[name]:
            mutating = "yes" if spec.mutating else ""
            lines.append(
                f"| `{spec.name}` | {mutating} | {_params(spec.input_schema)} | {_cell(spec.description)} |"
            )

    return "\n".join(lines) + "\n"


def render_site() -> str:
    """Site snippet: totals + toolset table, pulled into tools.md via pymdownx.snippets."""
    specs = core_registry().all()
    groups: dict[str, list] = {}
    for spec in specs:
        groups.setdefault(spec.toolset, []).append(spec)

    lines = [
        "<!-- Generated by scripts/tool_inventory.py from the registry — do not edit by hand. -->",
        "",
        f"**{len(specs)} tools** across **{len(groups)} toolsets**. `--profile` decides which",
        "toolsets a session exposes; `open_toolbox` / `close_toolbox` adjust it mid-session.",
        "",
        "| Toolset | Tools | Focus |",
        "|---|---|---|",
    ]
    for name in sorted(groups):
        lines.append(f"| `{name}` | {len(groups[name])} | {_cell(TOOLSET_DEFS.get(name, ''))} |")

    return "\n".join(lines) + "\n"


def _check(path: Path, text: str) -> bool:
    """Compare one generated target; print first mismatch. True = differs."""
    if not path.exists():
        print(f"Missing {path}; run generate without --check", file=sys.stderr)
        return True
    current = path.read_text(encoding="utf-8")
    if current == text:
        print(f"{path} matches registry")
        return False

    current_lines = current.splitlines()
    wanted_lines = text.splitlines()
    for index, (old, new) in enumerate(zip(current_lines, wanted_lines, strict=False), start=1):
        if old != new:
            print(f"{path}:{index} mismatch", file=sys.stderr)
            print(f"  repo:     {old[:120]}", file=sys.stderr)
            print(f"  generate: {new[:120]}", file=sys.stderr)
            break
    else:
        print(
            f"{path} line count mismatch: repo {len(current_lines)} / generated {len(wanted_lines)}",
            file=sys.stderr,
        )
    return True


def main(argv: list[str]) -> int:
    check = "--check" in argv
    targets = ((TARGET, render()), (SITE_TARGET, render_site()))

    if not check:
        for path, text in targets:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8", newline="\n")
            print(f"Wrote {path} ({len(text.splitlines())} lines)")
        return 0

    failed = False
    for path, text in targets:
        failed = _check(path, text) or failed
    if failed:
        print("Run `python scripts/tool_inventory.py` to regenerate", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
